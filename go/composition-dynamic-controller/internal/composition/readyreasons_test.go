// The JSON's shape. SchemaVersion is what a consumer refuses when it does not know it: bump it on any
// change a consumer could misread (a field renamed, removed or re-typed); adding a field is not one.
type reasonsFile struct {
	SchemaVersion int             `json:"schemaVersion"`
	Table         string          `json:"table"`
	GeneratedFrom string          `json:"generatedFrom"`
	Notice        string          `json:"notice"`
	Reasons       []reasonEntry   `json:"reasons"`
	Deprecated    []removedReason `json:"deprecated"`
}

type reasonEntry struct {
	Condition    string    `json:"condition"`
	Reason       string    `json:"reason"`
	Status       string    `json:"status"`
	Verdict      string    `json:"verdict"`
	Writer       string    `json:"writer"`
	Clearance    clearance `json:"clearance"`
	Meaning      string    `json:"meaning"`
	SinceVersion string    `json:"sinceVersion"`
	Action       string    `json:"action"`
	DetailFields []string  `json:"detailFields"`
}

type clearance struct {
	Kind   string `json:"kind"`
	Detail string `json:"detail"`
}

type removedReason struct {
	Condition string `json:"condition"`
	Reason    string `json:"reason"`
	Status    string `json:"status"`
	Writer    string `json:"writer"`
	RemovedIn string `json:"removedIn"`
	Note      string `json:"note"`
}

const readyReasonsNotice = "Generated by `go test ./internal/composition/ -run TestReadyReasonTableIsCurrent` in " +
	"go/composition-dynamic-controller, with UPDATE_READY_REASONS=1 to rewrite it, from the same registry as " +
	"docs/ready-reasons.md: one entry per row of that table, in its order. Do not edit by hand. " +
	"A reason is identified by condition, reason, status and writer. RENAMING OR REMOVING A REASON, OR CHANGING " +
	"ITS STATUS, IS BREAKING FOR CONSUMERS: a reason a release carried leaves the registry only through its " +
	"deprecated list, printed below with the release it was removed in, and a test refuses any other removal. " +
	"The set is closed except the ApiResolved entry whose reason is \"(authn's reason)\": authn's own refusal " +
	"reasons are passed through, an open set. verdict is how a parent composition's rollup reads a child " +
	"carrying the reason, on Ready only (\"—\" elsewhere). clearance.kind is steady, timer, next pass or " +
	"indefinite. sinceVersion is the first core-provider release whose source (with its pinned runtime) " +
	"contains the reason, a lower bound for a reason string another condition used first; \"unreleased\" until " +
	"a release ships it. action is what a person does, shown on screen: changing it is a UI change. " +
	"detailFields are the status fields carrying the reason's detail beyond the condition's own message. " +
	"Refuse a schemaVersion you do not know."

func renderReadyReasonsJSON(t *testing.T) string {
	t.Helper()
	f := reasonsFile{
		SchemaVersion: 1,
		Table:         "ready-reasons",
		GeneratedFrom: reflect.TypeOf(conditionreason.Reason{}).PkgPath(),
		Notice:        readyReasonsNotice,
		Reasons:       []reasonEntry{},
		Deprecated:    []removedReason{},
	}
	for _, r := range conditionreason.Table() {
		kind, note := clearanceParts(t, r)
		f.Reasons = append(f.Reasons, reasonEntry{
			Condition: r.Type(), Reason: r.String(), Status: string(r.Status()), Verdict: verdictOf(t, r),
			Writer: string(r.Writer()), Clearance: clearance{Kind: kind, Detail: note}, Meaning: r.Meaning(),
			SinceVersion: r.Since(), Action: r.Action(), DetailFields: append([]string{}, r.DetailFields()...),
		})
	}
	for _, d := range conditionreason.Deprecated() {
		f.Deprecated = append(f.Deprecated, removedReason{
			Condition: d.Condition, Reason: d.Reason, Status: string(d.Status), Writer: string(d.Writer),
			RemovedIn: d.RemovedIn, Note: d.Note,
		})
	}
	var b bytes.Buffer
	enc := json.NewEncoder(&b)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(f); err != nil {
		t.Fatal(err)
	}
	return b.String()
}

// clearanceTimers are the controller timers a Clearance note may name, with the variable that sets
// each (core-provider#522). The values are the code's own, so a changed default changes the file.
func clearanceTimers() map[string]string {
	return map[string]string{
		"{helmOperationTimeout}":  fmt.Sprintf("%s (%s)", helmOperationTimeout, helmTimeoutEnvvar),
		"{pendingOperationGrace}": fmt.Sprintf("%s (%s)", pendingOperationGrace, pendingGraceEnvvar),
		"{childTeardownGrace}":    fmt.Sprintf("%s (%s)", childTeardownGrace, childTeardownGraceEnvvar),
	}
}

func renderClearance(t *testing.T, r conditionreason.Reason) string {
	t.Helper()
	kind, note := clearanceParts(t, r)
	return "`" + kind + "`: " + note
}

// clearanceParts is r's expected-to-clear class and its note with the timers substituted: the two
// halves of the markdown's "expected to clear" cell, which docs/ready-reasons.json carries apart.
func clearanceParts(t *testing.T, r conditionreason.Reason) (kind, note string) {
	t.Helper()
	c := r.Clears()
	switch c.Kind {
	case conditionreason.Steady, conditionreason.Timer, conditionreason.NextPass, conditionreason.Indefinite:
	default:
		t.Fatalf("%s (%s): no expected-to-clear class (%q); every reason needs one", r, r.Writer(), c.Kind)
	}
	note = c.Note
	for key, value := range clearanceTimers() {
		note = strings.ReplaceAll(note, key, value)
	}
	if strings.ContainsAny(note, "{}") {
		t.Fatalf("%s (%s): note names an unknown timer: %q", r, r.Writer(), note)
	}
	if c.Kind == conditionreason.Timer && note == c.Note {
		t.Fatalf("%s (%s): a timer reason must name its timer", r, r.Writer())
	}
	return string(c.Kind), note
}

// The rendered table is committed, and stale is a failure: a reason added, removed, re-statused or
// re-classified by the rollup changes the file in the same change, where a consumer diffing tags
// sees it.
//
// Both renderings are checked, the markdown and the JSON (core-provider#667), each against its own
// committed file: either one stale fails.
func TestReadyReasonTableIsCurrent(t *testing.T) {
	for _, doc := range []struct {
		path string
		want string
	}{
		{readyReasonsDoc, renderReadyReasons(t)},
		{readyReasonsJSON, renderReadyReasonsJSON(t)},
	} {
		if os.Getenv("UPDATE_READY_REASONS") == "1" {
			if err := os.WriteFile(doc.path, []byte(doc.want), 0o644); err != nil {
				t.Fatal(err)
			}
		}
		got, err := os.ReadFile(doc.path)
		if err != nil {
			t.Errorf("%v (run with UPDATE_READY_REASONS=1 to create it)", err)
			continue
		}
		if string(got) != doc.want {
			t.Errorf("%s is stale: run `UPDATE_READY_REASONS=1 go test ./internal/composition/ -run TestReadyReasonTableIsCurrent` and commit it.\n--- want\n%s", doc.path, doc.want)
		}
	}
}

// The JSON is the markdown's table, entry for row: the same count, the same keys in the same order,
// and the same verdict and clearance. A renderer that dropped or reordered an entry would agree with
// its own committed file and still disagree with the table consumers already parse. Read from the
// committed files, as a consumer reads them.
func TestReadyReasonsJSONMatchesTheMarkdown(t *testing.T) {
	rows := markdownRows(t, readyReasonsDoc)
	raw, err := os.ReadFile(readyReasonsJSON)
	if err != nil {
		t.Fatal(err)
	}
	var f reasonsFile
	if err := json.Unmarshal(raw, &f); err != nil {
		t.Fatalf("%s: %v", readyReasonsJSON, err)
	}
	t.Logf("%d markdown rows, %d JSON entries", len(rows), len(f.Reasons))
	if len(rows) < 40 {
		t.Fatalf("only %d rows parsed from %s: the parser is not reading the table", len(rows), readyReasonsDoc)
	}
	if len(f.Reasons) != len(rows) {
		t.Fatalf("%s has %d entries, %s has %d rows", readyReasonsJSON, len(f.Reasons), readyReasonsDoc, len(rows))
	}
	for i, e := range f.Reasons {
		r := rows[i]
		got := []string{e.Condition, "`" + e.Reason + "`", e.Status, e.Writer, e.Verdict, "`" + e.Clearance.Kind + "`: " + e.Clearance.Detail, e.Meaning}
		want := []string{r["condition"], r["reason"], r["status"], r["writer"], r["parent verdict"], r["expected to clear"], r["written by"]}
		if strings.Join(got, "|") != strings.Join(want, "|") {
			t.Errorf("entry %d: JSON %q, markdown %q", i, got, want)
		}
	}
}

// markdownRows parses a reasons table by column NAME, as its consumers do.
func markdownRows(t *testing.T, path string) []map[string]string {
	t.Helper()
	raw, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	var header []string
	var out []map[string]string
	for _, line := range strings.Split(string(raw), "\n") {
		if !strings.HasPrefix(line, "| ") {
			continue
		}
		cells := strings.Split(strings.TrimSuffix(strings.TrimPrefix(line, "| "), " |"), " | ")
		if header == nil {
			header = cells
			continue
		}
		if len(cells) != len(header) {
			t.Fatalf("%s: a row with %d cells under %d columns: %q", path, len(cells), len(header), line)
		}
		row := map[string]string{}
		for i, c := range cells {
			row[header[i]] = c
		}
		out = append(out, row)
	}
	return out
}

// statusSchema is core-provider's statics/status.schema.json: the composition status fields the
// generated CRD declares. A field it does not declare is pruned by the apiserver, so a detail field
// absent from it would point a consumer at nothing.
const statusSchema = "../../../core-provider/internal/tools/crd/generation/statics/status.schema.json"

// Every reason carries the fields the JSON publishes (core-provider#667): a since-version, an action
// unless it is healthy or steady, and detail fields that the composition's status really declares.
func TestEveryReasonHasItsAuthoredFields(t *testing.T) {
	raw, err := os.ReadFile(statusSchema)
	if err != nil {
		t.Fatal(err)
	}
	var schema map[string]any
	if err := json.Unmarshal(raw, &schema); err != nil {
		t.Fatal(err)
	}
	declared := func(path string) bool {
		parts := strings.Split(path, ".")
		if parts[0] != "status" {
			return false
		}
		node := schema
		for _, p := range parts[1:] {
			props, _ := node["properties"].(map[string]any)
			next, ok := props[p].(map[string]any)
			if !ok {
				return false
			}
			node = next
		}
		return true
	}
	// Control: the resolver must find a field the cdc is known to write, and refuse one it is not,
	// or a pass below would say nothing.
	if !declared("status.installFailures.lastError") || declared("status.installFailures.nope") {
		t.Fatal("control: the status.schema.json resolver does not tell a declared field from an undeclared one")
	}
	withAction, withDetail := 0, 0
	for _, r := range conditionreason.Table() {
		key := r.Type() + "/" + string(r.Status()) + "/" + r.String() + "/" + string(r.Writer())
		if r.Since() == "" {
			t.Errorf("%s: no Since (a released tag, or %q)", key, conditionreason.Unreleased)
		}
		kind, _ := clearanceParts(t, r)
		if r.Action() == "" && verdictOf(t, r) != "healthy" && kind != string(conditionreason.Steady) {
			t.Errorf("%s: no Action; one is required unless the reason is healthy or steady", key)
		}
		if r.Action() != "" {
			withAction++
		}
		for _, p := range r.DetailFields() {
			withDetail++
			if !declared(p) {
				t.Errorf("%s: detail field %s is not declared in %s", key, p, statusSchema)
			}
		}
	}
	t.Logf("%d reasons, %d with an action, %d detail fields checked", len(conditionreason.Table()), withAction, withDetail)
	if withDetail == 0 {
		t.Fatal("no detail field was checked: the loop measured nothing")
	}
}

const runtimeConditionPkg = "github.com/krateo-platformops/unstructured-runtime/pkg/tools/unstructured/condition"

// readyConstructors are the runtime's constructors that build a Ready condition.
var readyConstructors = map[string]bool{
	"Available": true, "Creating": true, "Unavailable": true, "ZeroEvidence": true,
	"FailWithReason": true, "ReadyPaused": true, "ObserveFailed": true, "Deleting": true,
	// Synced (#528).
	"ReconcileSuccess": true, "ReconcileError": true, "ReconcilePaused": true, "ReconcileDeferred": true,
}

// conditionTypeNames are the condition types built only in internal/conditionreason (#528), as an
// identifier in this module (ConditionType*), a conditionreason selector (Type*), the runtime's
// Type* selector, or a literal.
var conditionTypeNames = map[string]bool{
	"Ready": true, "Synced": true, "ChartRenderable": true, "RBACComplete": true, "ApiResolved": true,
}
var conditionTypeIdents = map[string]bool{
	"ConditionTypeChartRenderable": true, "ConditionTypeRBACComplete": true, "ConditionTypeApiResolved": true,
}
var conditionTypeSelectors = map[string]bool{
	"TypeReady": true, "TypeSynced": true, "TypeChartRenderable": true, "TypeRBACComplete": true, "TypeApiResolved": true,
}

// readyConstructionSites lists every place in file that builds a Ready condition: a call to one of
// the runtime's Ready constructors, or a composite literal whose Type is the runtime's TypeReady or
// the literal "Ready".
func readyConstructionSites(fset *token.FileSet, file *ast.File) []string {
	alias := ""
	for _, imp := range file.Imports {
		if p, _ := strconv.Unquote(imp.Path.Value); p == runtimeConditionPkg {
			alias = "condition"
			if imp.Name != nil {
				alias = imp.Name.Name
			}
		}
	}
	isRuntime := func(e ast.Expr, name func(string) bool) bool {
		se, ok := e.(*ast.SelectorExpr)
		if !ok || alias == "" {
			return false
		}
		id, ok := se.X.(*ast.Ident)
		return ok && id.Name == alias && name(se.Sel.Name)
	}
	var out []string
	ast.Inspect(file, func(n ast.Node) bool {
		switch n := n.(type) {
		case *ast.CallExpr:
			if isRuntime(n.Fun, func(s string) bool { return readyConstructors[s] }) {
				out = append(out, fset.Position(n.Pos()).String())
			}
		case *ast.KeyValueExpr:
			k, ok := n.Key.(*ast.Ident)
			if !ok || k.Name != "Type" {
				return true
			}
			switch v := n.Value.(type) {
			case *ast.SelectorExpr:
				if conditionTypeSelectors[v.Sel.Name] {
					out = append(out, fset.Position(n.Pos()).String())
				}
			case *ast.Ident:
				if conditionTypeIdents[v.Name] {
					out = append(out, fset.Position(n.Pos()).String())
				}
			case *ast.BasicLit:
				if u, err := strconv.Unquote(v.Value); err == nil && conditionTypeNames[u] {
					out = append(out, fset.Position(n.Pos()).String())
				}
			}
		}
		return true
	})
	return out
}

// No Ready condition is built anywhere in the module except internal/conditionreason, so the closed
// set there is the whole set. The type alone cannot stop a metav1.Condition literal or a runtime
// constructor call; this does. Control: the same detector must find conditionreason's own constructions,
// or a zero here would say nothing.
func TestNoConditionBuiltOutsideConditionreason(t *testing.T) {
	root := "../.."
	fset := token.NewFileSet()
	scanned, controlHits := 0, 0
	// Files the walk must reach, or it measured less than the module: the entry point, the file
	// holding the Ready setters, and the package that is allowed to build them.
	mustVisit := map[string]bool{"main.go": false, "internal/composition/support.go": false, "internal/conditionreason/conditionreason.go": false}
	var violations []string
	err := filepath.WalkDir(root, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			if name := d.Name(); name == "vendor" || name == "testdata" || (strings.HasPrefix(name, ".") && path != root) {
				return filepath.SkipDir
			}
			return nil
		}
		if !strings.HasSuffix(path, ".go") || strings.HasSuffix(path, "_test.go") {
			return nil
		}
		file, err := parser.ParseFile(fset, path, nil, 0)
		if err != nil {
			return err
		}
		scanned++
		if rel, rerr := filepath.Rel(root, path); rerr == nil {
			if _, ok := mustVisit[filepath.ToSlash(rel)]; ok {
				mustVisit[filepath.ToSlash(rel)] = true
			}
		}
		sites := readyConstructionSites(fset, file)
		if filepath.Base(filepath.Dir(path)) == "conditionreason" {
			controlHits += len(sites)
			return nil
		}
		violations = append(violations, sites...)
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
	t.Logf("scanned %d files; control: %d constructions inside internal/conditionreason", scanned, controlHits)
	for f, seen := range mustVisit {
		if !seen {
			t.Fatalf("the scan never reached %s (%d files scanned): it is not measuring the module", f, scanned)
		}
	}
	if controlHits == 0 {
		t.Fatal("control: the detector found no construction inside internal/conditionreason, so a zero elsewhere says nothing")
	}
	for _, v := range violations {
		t.Errorf("condition built outside internal/conditionreason: %s (use a conditionreason.Reason)", v)
	}
}
