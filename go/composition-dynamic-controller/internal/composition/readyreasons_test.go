// readyReasonsDoc is the rendered table, at a path a consumer can read from any tag (#515).
const readyReasonsDoc = "../../../../docs/ready-reasons.md"

// rollupVerdict is how THIS cdc's child rollup reads a composition child carrying r: what a parent
// composition concludes about it. Computed by krateoReady, never written by hand.
func rollupVerdict(t *testing.T, r readyreason.Reason) string {
	t.Helper()
	child := &unstructured.Unstructured{Object: map[string]any{
		"apiVersion": "composition.krateo.io/v1-0-0", "kind": "Child",
		"status": map[string]any{"conditions": []any{map[string]any{
			"type": "Ready", "status": string(r.Status()), "reason": r.String(),
		}}},
	}}
	switch s := krateoReady(child); s {
	case childHealthy:
		return "healthy"
	case childConverging:
		return "converging"
	case childFailed:
		return "failed"
	case childUnevaluated:
		return "unevaluated (rolls up as healthy)"
	default:
		t.Fatalf("%s: krateoReady returned state %d, which this table has no word for", r, s)
		return ""
	}
}

func renderReadyReasons(t *testing.T) string {
	var b strings.Builder
	b.WriteString(`---
type: API
title: core-provider — Ready reasons of a composition
description: Every reason a composition's Ready condition can carry, with its status, writer and how a parent composition's rollup reads it. Generated from the code.
resource: oci://ghcr.io/krateo-platformops/charts/core-provider
tags: [api, conditions, ready, rollup]
timestamp: 2026-11-15T00:00:00Z
---

# Ready reasons of a composition

Generated by ` + "`go test ./internal/composition/ -run TestReadyReasonTableIsCurrent`" + ` in
go/composition-dynamic-controller, with ` + "`UPDATE_READY_REASONS=1`" + ` to rewrite it. Do not edit by hand.

Every reason a composition's ` + "`Ready`" + ` condition can carry (core-provider#515). The set is CLOSED: the
composition-dynamic-controller builds every Ready condition through ` + "`internal/readyreason`" + `, whose
values cannot be constructed elsewhere, and a test refuses any other construction in the module.
The unstructured-runtime rows are written by the runtime on the same compositions.

- **status** is the status the reason is always written with.
- **parent verdict** is how this controller's child rollup reads a composition child carrying it,
  computed by ` + "`krateoReady`" + `. ` + "`converging`" + ` keeps the parent ` + "`Ready=False/Creating`" + `.
- **written by** names the code that writes it.

| reason | status | writer | parent verdict | written by |
|---|---|---|---|---|
`)
	for _, r := range readyreason.Table() {
		fmt.Fprintf(&b, "| `%s` | %s | %s | %s | %s |\n", r, r.Status(), r.Writer(), rollupVerdict(t, r), r.Meaning())
	}
	return b.String()
}

// The rendered table is committed, and stale is a failure: a reason added, removed, re-statused or
// re-classified by the rollup changes the file in the same change, where a consumer diffing tags
// sees it.
func TestReadyReasonTableIsCurrent(t *testing.T) {
	want := renderReadyReasons(t)
	if os.Getenv("UPDATE_READY_REASONS") == "1" {
		if err := os.WriteFile(readyReasonsDoc, []byte(want), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	got, err := os.ReadFile(readyReasonsDoc)
	if err != nil {
		t.Fatalf("%v (run with UPDATE_READY_REASONS=1 to create it)", err)
	}
	if string(got) != want {
		t.Fatalf("%s is stale: run `UPDATE_READY_REASONS=1 go test ./internal/composition/ -run TestReadyReasonTableIsCurrent` and commit it.\n--- want\n%s", readyReasonsDoc, want)
	}
}

const runtimeConditionPkg = "github.com/krateo-platformops/unstructured-runtime/pkg/tools/unstructured/condition"

// readyConstructors are the runtime's constructors that build a Ready condition.
var readyConstructors = map[string]bool{
	"Available": true, "Creating": true, "Unavailable": true, "ZeroEvidence": true,
	"FailWithReason": true, "ReadyPaused": true, "ObserveFailed": true, "Deleting": true,
}

// readyConstructionSites lists every place in file that builds a Ready condition: a call to one of
// the runtime's Ready constructors, or a composite literal whose Type is the runtime's TypeReady or
// the literal "Ready".
func readyConstructionSites(fset *token.FileSet, file *ast.File) []string {
	alias := ""
	for _, imp := range file.Imports {
		if p, _ := strconv.Unquote(imp.Path.Value); p == runtimeConditionPkg {
			alias = "condition"
			if imp.Name != nil {
				alias = imp.Name.Name
			}
		}
	}
	isRuntime := func(e ast.Expr, name func(string) bool) bool {
		se, ok := e.(*ast.SelectorExpr)
		if !ok || alias == "" {
			return false
		}
		id, ok := se.X.(*ast.Ident)
		return ok && id.Name == alias && name(se.Sel.Name)
	}
	var out []string
	ast.Inspect(file, func(n ast.Node) bool {
		switch n := n.(type) {
		case *ast.CallExpr:
			if isRuntime(n.Fun, func(s string) bool { return readyConstructors[s] }) {
				out = append(out, fset.Position(n.Pos()).String())
			}
		case *ast.KeyValueExpr:
			k, ok := n.Key.(*ast.Ident)
			if !ok || k.Name != "Type" {
				return true
			}
			if isRuntime(n.Value, func(s string) bool { return s == "TypeReady" }) {
				out = append(out, fset.Position(n.Pos()).String())
			}
			if bl, ok := n.Value.(*ast.BasicLit); ok && bl.Value == `"Ready"` {
				out = append(out, fset.Position(n.Pos()).String())
			}
		}
		return true
	})
	return out
}

// No Ready condition is built anywhere in the module except internal/readyreason, so the closed
// set there is the whole set. The type alone cannot stop a metav1.Condition literal or a runtime
// constructor call; this does. Control: the same detector must find readyreason's own constructions,
// or a zero here would say nothing.
func TestNoReadyConditionBuiltOutsideReadyreason(t *testing.T) {
	root := "../.."
	fset := token.NewFileSet()
	scanned, controlHits := 0, 0
	// Files the walk must reach, or it measured less than the module: the entry point, the file
	// holding the Ready setters, and the package that is allowed to build them.
	mustVisit := map[string]bool{"main.go": false, "internal/composition/support.go": false, "internal/readyreason/readyreason.go": false}
	var violations []string
	err := filepath.WalkDir(root, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			if name := d.Name(); name == "vendor" || name == "testdata" || (strings.HasPrefix(name, ".") && path != root) {
				return filepath.SkipDir
			}
			return nil
		}
		if !strings.HasSuffix(path, ".go") || strings.HasSuffix(path, "_test.go") {
			return nil
		}
		file, err := parser.ParseFile(fset, path, nil, 0)
		if err != nil {
			return err
		}
		scanned++
		if rel, rerr := filepath.Rel(root, path); rerr == nil {
			if _, ok := mustVisit[filepath.ToSlash(rel)]; ok {
				mustVisit[filepath.ToSlash(rel)] = true
			}
		}
		sites := readyConstructionSites(fset, file)
		if filepath.Base(filepath.Dir(path)) == "readyreason" {
			controlHits += len(sites)
			return nil
		}
		violations = append(violations, sites...)
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
	t.Logf("scanned %d files; control: %d constructions inside internal/readyreason", scanned, controlHits)
	for f, seen := range mustVisit {
		if !seen {
			t.Fatalf("the scan never reached %s (%d files scanned): it is not measuring the module", f, scanned)
		}
	}
	if controlHits == 0 {
		t.Fatal("control: the detector found no construction inside internal/readyreason, so a zero elsewhere says nothing")
	}
	for _, v := range violations {
		t.Errorf("Ready condition built outside internal/readyreason: %s (use a readyreason.Reason)", v)
	}
}
