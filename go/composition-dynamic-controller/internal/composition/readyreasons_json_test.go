// jsonVerdict maps a markdown verdict cell to the JSON's verdict and rollsUpAs. The cell
// "unevaluated (rolls up as healthy)" becomes verdict "unevaluated" with rollsUpAs "healthy". A cell
// this mapping does not know fails the render rather than publishing prose as an enum value.
func jsonVerdict(t *testing.T, cell string) (*string, string) {
	t.Helper()
	if cell == "—" {
		return nil, ""
	}
	if rest, ok := strings.CutPrefix(cell, "unevaluated (rolls up as "); ok {
		as, ok := strings.CutSuffix(rest, ")")
		if !ok || !jsonVerdicts[as] || as == "unevaluated" {
			t.Fatalf("verdict cell %q: no JSON verdict for it", cell)
		}
		v := "unevaluated"
		return &v, as
	}
	if !jsonVerdicts[cell] || cell == "unevaluated" {
		t.Fatalf("verdict cell %q: no JSON verdict for it", cell)
	}
	return &cell, ""
}

func renderReadyReasonsJSON(t *testing.T) string {
	t.Helper()
	var single []reasonEntry
	for _, r := range conditionreason.Table() {
		kind, note := clearanceParts(t, r)
		verdict, rollsUpAs := jsonVerdict(t, verdictOf(t, r))
		var reason *string
		if r.ReasonFrom() == "" {
			s := r.String()
			reason = &s
		}
		c := reasonCase{
			Writer: string(r.Writer()), Meaning: r.Meaning(), Clearance: clearance{Kind: kind, Detail: note},
			SinceVersion: r.Since(), Action: r.Action(), Actors: actorStrings(r.Actors()), Control: r.Control(), DetailFields: append([]string{}, r.DetailFields()...),
		}
		if a := r.Annotation(); a != nil {
			c.Annotation = &jsonAnnotation{Name: a.Name, Op: string(a.Op), Value: a.Value}
		}
		single = append(single, reasonEntry{
			Condition: r.Type(), Reason: reason, ReasonFrom: r.ReasonFrom(), Status: string(r.Status()),
			Verdict: verdict, RollsUpAs: rollsUpAs, Writers: []string{c.Writer}, Cases: []reasonCase{c},
		})
	}
	f := reasonsFile{
		SchemaVersion: 1,
		Table:         "ready-reasons",
		GeneratedFrom: reflect.TypeOf(conditionreason.Reason{}).PkgPath(),
		Notice:        readyReasonsNotice,
		Reasons:       mergeEntries(t, single),
		Deprecated:    []removedReason{},
	}
	for _, d := range conditionreason.Deprecated() {
		f.Deprecated = append(f.Deprecated, removedReason{
			Condition: d.Condition, Reason: d.Reason, Status: string(d.Status), Writer: string(d.Writer),
			RemovedIn: d.RemovedIn, Note: d.Note,
		})
	}
	return encodeReasons(t, f)
}

// The JSON holds the markdown's rows, every one as a case of exactly one entry, with the cells' own
// values, and one entry per distinct condition, status and reason. A renderer that dropped, changed
// or duplicated a row would agree with its own committed file and still disagree with the table
// consumers already parse. Read from the committed files, as a consumer reads them.
func TestReadyReasonsJSONMatchesTheMarkdown(t *testing.T) {
	md, keys := mdRowsAsCases(t, readyReasonsDoc, []string{"condition", "reason", "status", "writer", "parent verdict", "expected to clear", "written by"})
	raw, err := os.ReadFile(readyReasonsJSON)
	if err != nil {
		t.Fatal(err)
	}
	var f reasonsFile
	if err := json.Unmarshal(raw, &f); err != nil {
		t.Fatalf("%s: %v", readyReasonsJSON, err)
	}
	var js []string
	for _, e := range f.Reasons {
		for _, c := range e.Cases {
			js = append(js, strings.Join([]string{e.Condition, markdownReason(e), e.Status, c.Writer, markdownVerdict(e.Verdict, e.RollsUpAs),
				"`" + c.Clearance.Kind + "`: " + c.Clearance.Detail, c.Meaning}, " | "))
		}
	}
	sort.Strings(js)
	t.Logf("%d markdown rows over %d distinct condition/status/reason; %d JSON entries holding %d cases", len(md), keys, len(f.Reasons), len(js))
	if len(md) < 40 {
		t.Fatalf("only %d rows parsed from %s: the parser is not reading the table", len(md), readyReasonsDoc)
	}
	if len(f.Reasons) != keys {
		t.Errorf("%s has %d entries for %d distinct condition/status/reason in %s", readyReasonsJSON, len(f.Reasons), keys, readyReasonsDoc)
	}
	if strings.Join(js, "\n") != strings.Join(md, "\n") {
		t.Errorf("the JSON's cases are not the markdown's rows:\n--- markdown\n%s\n--- JSON\n%s", strings.Join(md, "\n"), strings.Join(js, "\n"))
	}
}

// The JSON is what a consumer can rely on, in the rendering and in the committed file: verdicts in
// the enum or null, clearance kinds in the four, one entry per condition, status and reason, a null
// reason only with reasonFrom, and each entry presenting its longest-lasting case. CONTROL: the cdc
// and unstructured-runtime both write Ready=False/Creating, so at least one entry must have two cases.
func TestReadyReasonsJSONIsWellFormed(t *testing.T) {
	committed, err := os.ReadFile(readyReasonsJSON)
	if err != nil {
		t.Fatal(err)
	}
	for _, src := range []struct{ name, body string }{{"rendered", renderReadyReasonsJSON(t)}, {readyReasonsJSON, string(committed)}} {
		if _, merged := checkReasonsJSON(t, src.name, src.body); merged == 0 {
			t.Errorf("%s: control: no entry has two writers, and Ready=False/Creating has two", src.name)
		}
	}
}

// The JSON's shape. SchemaVersion is what a consumer refuses when it does not know it: bump it on any
// change a consumer could misread (a field renamed, removed or re-typed); adding a field is not one.
type reasonsFile struct {
	SchemaVersion int             `json:"schemaVersion"`
	Table         string          `json:"table"`
	GeneratedFrom string          `json:"generatedFrom"`
	Notice        string          `json:"notice"`
	Reasons       []reasonEntry   `json:"reasons"`
	Deprecated    []removedReason `json:"deprecated"`
}

// reasonEntry is one condition, status and reason: what a consumer can see on an object. Where two
// writers write the same one (the markdown has a row per writer), it holds a case per writer, and its
// own clearance, action and detail fields are the ones a consumer that cannot tell the writers apart
// should present.
type reasonEntry struct {
	Condition    string          `json:"condition"`
	Reason       *string         `json:"reason"`
	ReasonFrom   string          `json:"reasonFrom,omitempty"`
	Status       string          `json:"status"`
	Verdict      *string         `json:"verdict"`
	RollsUpAs    string          `json:"rollsUpAs,omitempty"`
	Writers      []string        `json:"writers"`
	Clearance    clearance       `json:"clearance"`
	SinceVersion string          `json:"sinceVersion"`
	Action       string          `json:"action"`
	Actors       []string        `json:"actors,omitempty"`
	Control      string          `json:"control,omitempty"`
	Annotation   *jsonAnnotation `json:"annotation,omitempty"`
	DetailFields []string        `json:"detailFields"`
	Cases        []reasonCase    `json:"cases"`
}

// reasonCase is one writer's row of the markdown.
type reasonCase struct {
	Writer       string          `json:"writer"`
	Meaning      string          `json:"meaning"`
	Clearance    clearance       `json:"clearance"`
	SinceVersion string          `json:"sinceVersion"`
	Action       string          `json:"action"`
	Actors       []string        `json:"actors,omitempty"`
	Control      string          `json:"control,omitempty"`
	Annotation   *jsonAnnotation `json:"annotation,omitempty"`
	DetailFields []string        `json:"detailFields"`
}

// jsonAnnotation is the annotation a person's step changes: its key, the operation (remove, set or
// edit), and, for set only, the value to set.
type jsonAnnotation struct {
	Name  string  `json:"name"`
	Op    string  `json:"op"`
	Value *string `json:"value,omitempty"`
}

// sameAnnotation reports whether two annotations are the same step.
func sameAnnotation(a, b *jsonAnnotation) bool {
	if a == nil || b == nil {
		return a == b
	}
	return a.Name == b.Name && a.Op == b.Op && (a.Value == nil) == (b.Value == nil) && (a.Value == nil || *a.Value == *b.Value)
}

// annotationOps are the operations a step can do to an annotation: remove and edit carry no value,
// set requires one.
var annotationOps = map[string]bool{"remove": true, "set": true, "edit": true}

// annotationProblem says what is wrong with an annotation's op and value, or "".
func annotationProblem(a *jsonAnnotation) string {
	switch {
	case !annotationOps[a.Op]:
		return fmt.Sprintf("op %q is not one of remove, set, edit", a.Op)
	case a.Op == "set" && a.Value == nil:
		return "op set without a value"
	case a.Op != "set" && a.Value != nil:
		return fmt.Sprintf("op %s with a value (%q): only set carries one", a.Op, *a.Value)
	}
	return ""
}

// actorStrings is a registry's actors as the JSON prints them.
func actorStrings[A ~string](as []A) []string {
	var out []string
	for _, a := range as {
		out = append(out, string(a))
	}
	return out
}

// actorsEnum is who can act: you (the person reading the portal), admin (an admin of the cluster) and
// maintainers (the blueprint's).
var actorsEnum = map[string]bool{"you": true, "admin": true, "maintainers": true}

// needsActors: an action that is not a wait has someone who must act, and so does a wait whose step
// is a portal control; a wait otherwise, and a row with no action, has none.
func needsActors(action, control string) bool {
	return action != "" && (!strings.HasPrefix(action, "Wait") || control != "")
}

// actorsProblem says what is wrong with an action's actors, or "" (#667, observability): present
// exactly when needed, every value in the enum, and a control row's actors include someone who
// stands at the portal (you or admin), never maintainers alone.
func actorsProblem(action, control string, actors []string) string {
	if needsActors(action, control) != (len(actors) > 0) {
		return fmt.Sprintf("actors %v for action %q (control %q): needed exactly on a non-wait action or a wait with a control", actors, action, control)
	}
	atPortal := false
	for _, a := range actors {
		if !actorsEnum[a] {
			return fmt.Sprintf("actor %q is not one of you, admin, maintainers", a)
		}
		atPortal = atPortal || a == "you" || a == "admin"
	}
	if control != "" && !atPortal {
		return fmt.Sprintf("control %q with actors %v: someone at the portal (you or admin) presses it", control, actors)
	}
	return ""
}

// portalControls are the portal's controls an action may name, by on-screen label (portal main): the
// composition page's Pause/Resume and the resource page's "Clear create-pending annotation". The
// composition page's Sync button only re-reads data and is never one.
var portalControls = map[string]bool{"Resume": true, "Clear create-pending annotation": true}

type clearance struct {
	Kind   string `json:"kind"`
	Detail string `json:"detail"`
}

type removedReason struct {
	Condition string `json:"condition"`
	Reason    string `json:"reason"`
	Status    string `json:"status"`
	Writer    string `json:"writer"`
	RemovedIn string `json:"removedIn"`
	Note      string `json:"note"`
}

// jsonVerdicts are the JSON's verdict values: a closed enum a consumer can switch on, where the
// markdown cell is prose. The markdown's "—" (a condition the rollup does not read) is JSON null.
var jsonVerdicts = map[string]bool{"healthy": true, "converging": true, "failed": true, "unevaluated": true}

// clearKinds are the four clearance kinds, ranked by how long each lasts: an entry with two cases
// presents the longer-lasting one.
var clearKinds = map[string]int{"steady": 0, "next pass": 1, "timer": 2, "indefinite": 3}

// markdownVerdict is the markdown cell a JSON entry's verdict and rollsUpAs stand for: the JSON
// mapping inverted, so the JSON-to-markdown comparison checks the mapping as well as the rows.
func markdownVerdict(verdict *string, rollsUpAs string) string {
	switch {
	case verdict == nil:
		return "—"
	case *verdict == "unevaluated":
		return "unevaluated (rolls up as " + rollsUpAs + ")"
	}
	return *verdict
}

// markdownReason is the markdown's reason cell for an entry: a family passed through from another
// component is printed as "(<component>'s reason)".
func markdownReason(e reasonEntry) string {
	if e.Reason == nil {
		return "`(" + e.ReasonFrom + "'s reason)`"
	}
	return "`" + *e.Reason + "`"
}

// entryKey is what a consumer looks an object's condition up by.
func entryKey(e reasonEntry) string {
	r := "from:" + e.ReasonFrom
	if e.Reason != nil {
		r = *e.Reason
	}
	return e.Condition + "/" + e.Status + "/" + r
}

// releaseBefore orders two sinceVersions: X.Y.Z numerically, and "unreleased" after every release.
func releaseBefore(a, b string) bool {
	parse := func(v string) []int {
		if v == "unreleased" {
			return []int{1 << 30}
		}
		var out []int
		for _, p := range strings.Split(v, ".") {
			n, _ := strconv.Atoi(p)
			out = append(out, n)
		}
		return out
	}
	pa, pb := parse(a), parse(b)
	for i := 0; i < len(pa) && i < len(pb); i++ {
		if pa[i] != pb[i] {
			return pa[i] < pb[i]
		}
	}
	return len(pa) < len(pb)
}

// mergeEntries folds single-case entries, one per markdown row, into one entry per condition, status
// and reason, in the order each first appears. An entry's clearance and action are those of its
// longest-lasting case (the first on a tie), its detail fields the union of its cases', and its
// sinceVersion the earliest. Two cases of one entry must agree on the verdict: the rollup reads the
// reason, not the writer.
func mergeEntries(t *testing.T, single []reasonEntry) []reasonEntry {
	t.Helper()
	var out []reasonEntry
	at := map[string]int{}
	for _, e := range single {
		k := entryKey(e)
		i, seen := at[k]
		if !seen {
			at[k] = len(out)
			out = append(out, e)
			continue
		}
		m := &out[i]
		if markdownVerdict(m.Verdict, m.RollsUpAs) != markdownVerdict(e.Verdict, e.RollsUpAs) {
			t.Fatalf("%s: writers %v and %v disagree on the verdict", k, m.Writers, e.Writers)
		}
		m.Writers = append(m.Writers, e.Writers...)
		m.Cases = append(m.Cases, e.Cases...)
	}
	for i := range out {
		e := &out[i]
		top := e.Cases[0]
		e.DetailFields = []string{}
		seen := map[string]bool{}
		e.SinceVersion = top.SinceVersion
		for _, c := range e.Cases {
			if clearKinds[c.Clearance.Kind] > clearKinds[top.Clearance.Kind] {
				top = c
			}
			for _, f := range c.DetailFields {
				if !seen[f] {
					seen[f] = true
					e.DetailFields = append(e.DetailFields, f)
				}
			}
			if releaseBefore(c.SinceVersion, e.SinceVersion) {
				e.SinceVersion = c.SinceVersion
			}
		}
		e.Clearance, e.Action, e.Actors, e.Control, e.Annotation = top.Clearance, top.Action, top.Actors, top.Control, top.Annotation
	}
	return out
}

func encodeReasons(t *testing.T, f reasonsFile) string {
	t.Helper()
	var b bytes.Buffer
	enc := json.NewEncoder(&b)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(f); err != nil {
		t.Fatal(err)
	}
	return b.String()
}

// mdRowsAsCases parses a reasons table by column NAME, as its consumers do, into one tuple per row.
func mdRowsAsCases(t *testing.T, path string, cols []string) ([]string, int) {
	t.Helper()
	raw, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	var header []string
	var out []string
	keys := map[string]bool{}
	for _, line := range strings.Split(string(raw), "\n") {
		if !strings.HasPrefix(line, "| ") {
			continue
		}
		cells := strings.Split(strings.TrimSuffix(strings.TrimPrefix(line, "| "), " |"), " | ")
		if header == nil {
			header = cells
			continue
		}
		if len(cells) != len(header) {
			t.Fatalf("%s: a row with %d cells under %d columns: %q", path, len(cells), len(header), line)
		}
		row := map[string]string{}
		for i, c := range cells {
			row[header[i]] = c
		}
		var tuple []string
		for _, c := range cols {
			v, ok := row[c]
			if !ok {
				t.Fatalf("%s: no %q column", path, c)
			}
			tuple = append(tuple, v)
		}
		out = append(out, strings.Join(tuple, " | "))
		keys[row["condition"]+"/"+row["status"]+"/"+row["reason"]] = true
	}
	sort.Strings(out)
	return out, len(keys)
}

// checkReasonsJSON is the well-formedness a consumer relies on, over a rendered or committed file,
// decoded twice: as generic maps (as a consumer decodes it: no struct of this test's own can hide a
// missing or mistyped key) and as the struct, for the merge's arithmetic. It returns the verdict
// counts and the number of entries with more than one case.
func checkReasonsJSON(t *testing.T, name, body string) (map[string]int, int) {
	t.Helper()
	var raw struct {
		Reasons []map[string]any `json:"reasons"`
	}
	if err := json.Unmarshal([]byte(body), &raw); err != nil {
		t.Fatalf("%s: %v", name, err)
	}
	counts := map[string]int{}
	for i, e := range raw.Reasons {
		id := fmt.Sprintf("%s entry %d (%v/%v/%v)", name, i, e["condition"], e["status"], e["reason"])
		v, present := e["verdict"]
		if !present {
			t.Errorf("%s: no verdict key", id)
			continue
		}
		word := "null"
		if v != nil {
			s, ok := v.(string)
			if !ok || !jsonVerdicts[s] {
				t.Errorf("%s: verdict %#v is not one of healthy, converging, failed, unevaluated or null", id, v)
				continue
			}
			word = s
		}
		counts[word]++
		if (v == nil) != (e["condition"] != "Ready") {
			t.Errorf("%s: verdict %v; null is for, and only for, a condition the rollup does not read", id, v)
		}
		as, hasAs := e["rollsUpAs"]
		if hasAs != (word == "unevaluated") || (hasAs && as != "healthy") {
			t.Errorf("%s: rollsUpAs %v with verdict %s", id, as, word)
		}
		reason, hasReason := e["reason"]
		from, hasFrom := e["reasonFrom"]
		if !hasReason || (reason == nil) != hasFrom || (hasFrom && from != "authn") {
			t.Errorf("%s: reason %#v with reasonFrom %#v: reason is null exactly when reasonFrom names the component (authn)", id, reason, from)
		}
		kinds := []any{}
		if c, ok := e["clearance"].(map[string]any); ok {
			kinds = append(kinds, c["kind"])
		} else {
			t.Errorf("%s: no clearance object", id)
		}
		cases, _ := e["cases"].([]any)
		for _, c := range cases {
			cm, _ := c.(map[string]any)
			cc, _ := cm["clearance"].(map[string]any)
			kinds = append(kinds, cc["kind"])
		}
		for _, k := range kinds {
			s, _ := k.(string)
			if _, ok := clearKinds[s]; !ok {
				t.Errorf("%s: clearance kind %#v is not one of steady, timer, next pass, indefinite", id, k)
			}
		}
	}
	var f reasonsFile
	if err := json.Unmarshal([]byte(body), &f); err != nil {
		t.Fatalf("%s: %v", name, err)
	}
	merged := 0
	keys := map[string]bool{}
	for i, e := range f.Reasons {
		k := entryKey(e)
		if keys[k] {
			t.Errorf("%s entry %d: %s appears twice: one entry per condition, status and reason", name, i, k)
		}
		keys[k] = true
		if len(e.Cases) == 0 || len(e.Writers) != len(e.Cases) {
			t.Errorf("%s: %d writers for %d cases", k, len(e.Writers), len(e.Cases))
			continue
		}
		if len(e.Cases) > 1 {
			merged++
		}
		top := e.Cases[0]
		for j, c := range e.Cases {
			if e.Writers[j] != c.Writer {
				t.Errorf("%s: writers[%d] %s, cases[%d].writer %s", k, j, e.Writers[j], j, c.Writer)
			}
			if clearKinds[c.Clearance.Kind] > clearKinds[top.Clearance.Kind] {
				top = c
			}
		}
		if e.Clearance != top.Clearance || e.Action != top.Action || strings.Join(e.Actors, ",") != strings.Join(top.Actors, ",") ||
			e.Control != top.Control || !sameAnnotation(e.Annotation, top.Annotation) {
			t.Errorf("%s: presents clearance %v, action %q, control %q, annotation %v; its longest-lasting case (%s) has %v, %q, %q, %v",
				k, e.Clearance, e.Action, e.Control, e.Annotation, top.Writer, top.Clearance, top.Action, top.Control, top.Annotation)
		}
		// The top level is what the portal shows (#667): set on every entry that needs one.
		if e.Clearance.Kind == "" || e.Clearance.Detail == "" {
			t.Errorf("%s: no top-level clearance", k)
		}
		if e.Action == "" && markdownVerdict(e.Verdict, e.RollsUpAs) != "healthy" && e.Clearance.Kind != "steady" {
			t.Errorf("%s: no top-level action, and it is neither healthy nor steady", k)
		}
		for _, c := range append([]reasonCase{{Writer: "(entry)", Action: e.Action, Actors: e.Actors, Control: e.Control, Annotation: e.Annotation}}, e.Cases...) {
			if why := actorsProblem(c.Action, c.Control, c.Actors); why != "" {
				t.Errorf("%s (%s): %s", k, c.Writer, why)
			}
			if c.Control != "" && !portalControls[c.Control] {
				t.Errorf("%s (%s): control %q is not one of the portal's controls %v", k, c.Writer, c.Control, portalControls)
			}
			if c.Annotation != nil && !strings.HasPrefix(c.Annotation.Name, "krateo.io/") {
				t.Errorf("%s (%s): annotation %q is not a krateo.io/ key", k, c.Writer, c.Annotation.Name)
			}
			if c.Annotation != nil {
				if why := annotationProblem(c.Annotation); why != "" {
					t.Errorf("%s (%s): annotation %s: %s", k, c.Writer, c.Annotation.Name, why)
				}
			}
		}
	}
	t.Logf("%s: %d entries (%d with more than one writer), verdicts %v", name, len(f.Reasons), merged, counts)
	if counts["null"] == 0 || counts["healthy"] == 0 {
		t.Errorf("%s: control: verdicts %v have no null or no healthy entry; the check measured nothing", name, counts)
	}
	return counts, merged
}
