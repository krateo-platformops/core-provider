// cdReadyReasonsDoc is the rendered table, at a path a consumer can read from any tag.
const cdReadyReasonsDoc = "../../../../docs/cd-ready-reasons.md"

func renderCDReadyReasons() string {
	var b strings.Builder
	// THE COLUMN NAMES ARE A CONTRACT, the same as docs/ready-reasons.md's: `condition`, `reason`,
	// `status`, `writer` and `parent verdict`. The portal's CI gate and installer's vendored
	// classifier parse them by NAME (frontend and installer, 2026-11-16), and the cdc's
	// TestCompositionDefinitionReasonsRollUpAsDeclared reads `parent verdict` from this file.
	// Reordering or adding columns is fine; renaming or removing one breaks all three.
	b.WriteString(`---
type: API
title: core-provider — condition reasons of a CompositionDefinition
description: Every reason a CompositionDefinition's conditions can carry (Ready, Synced, and every other type core-provider writes), with its status, writer and, for Ready, how a parent composition's rollup reads it. Generated from the code.
resource: oci://ghcr.io/krateo-platformops/charts/core-provider
tags: [api, conditions, ready, rollup, compositiondefinition]
timestamp: 2026-11-16T00:00:00Z
---

# Condition reasons of a CompositionDefinition

Generated by ` + "`go test ./internal/cdreason/ -run TestCDReadyReasonTableIsCurrent`" + ` in go/core-provider,
with ` + "`UPDATE_READY_REASONS=1`" + ` to rewrite it. Do not edit by hand. A composition's reasons are in
[ready-reasons.md](ready-reasons.md); the two are separate sets, and a reason string can appear in both.

Every reason a CompositionDefinition's conditions can carry: ` + "`Ready`" + `, ` + "`Synced`" + `, and every other type
core-provider writes (` + "`ControllerActive`" + `, ` + "`SchemaFullyEnforced`" + `, ` + "`SpecSchemaCurrent`" + `, ` + "`ApiRefRBACComplete`" + `,
` + "`AuthnDelegation`" + `, ` + "`AuthnMappingApplied`" + `). core-provider builds every one of them through
` + "`internal/cdreason`" + `, whose values cannot be constructed elsewhere, and two tests refuse any other
construction in the module (one for Ready, one for any condition). The provider-runtime rows are
written by the managed reconciler on the same objects. The set is CLOSED.

- **status** is the status the reason is always written with.
- **parent verdict**, on ` + "`Ready`" + ` rows only, is how a parent composition's child rollup reads a
  CompositionDefinition carrying it. A definition IS such a child: installer's umbrella composition
  renders most of a cluster's definitions, and the composition-dynamic-controller's rollup reads every
  ` + "`*.krateo.io`" + ` child's Ready (` + "`krateoEval`" + `). core-provider declares it, and the cdc's
  ` + "`TestCompositionDefinitionReasonsRollUpAsDeclared`" + ` reads this file and fails when ` + "`krateoEval`" + `
  disagrees with a row. ` + "`converging`" + ` keeps the parent ` + "`Ready=False/Creating`" + ` while it lasts, and
  ` + "`Creating`" + ` has no deadline of its own. The rollup reads only ` + "`Ready`" + `, so every other type shows ` + "`—`" + `.
- **written by** says when it is written.

| condition | reason | status | writer | parent verdict | written by |
|---|---|---|---|---|---|
`)
	for _, r := range Table() {
		fmt.Fprintf(&b, "| %s | `%s` | %s | %s | %s | %s |\n", r.Type(), r, r.Status(), r.Writer(), r.ParentVerdict(), r.Meaning())
	}
	return b.String()
}

// The rendered table is committed, and stale is a failure: a reason added, removed, re-statused or
// re-classified changes the file in the same change, where a consumer diffing tags sees it. Both
// renderings are checked, the markdown and the JSON (#667), each against its own committed file:
// either one stale fails.
func TestCDReadyReasonTableIsCurrent(t *testing.T) {
	for _, doc := range []struct {
		path string
		want string
	}{
		{cdReadyReasonsDoc, renderCDReadyReasons()},
		{cdReadyReasonsJSON, renderCDReadyReasonsJSON(t)},
	} {
		if os.Getenv("UPDATE_READY_REASONS") == "1" {
			if err := os.WriteFile(doc.path, []byte(doc.want), 0o644); err != nil {
				t.Fatal(err)
			}
		}
		got, err := os.ReadFile(doc.path)
		if err != nil {
			t.Errorf("%v (run with UPDATE_READY_REASONS=1 to create it)", err)
			continue
		}
		if string(got) != doc.want {
			t.Errorf("%s is stale: run `UPDATE_READY_REASONS=1 go test ./internal/cdreason/ -run TestCDReadyReasonTableIsCurrent` and commit it.\n--- want\n%s", doc.path, doc.want)
		}
	}
}

// actorPhrase is how an action names who acts (#667): you (the person reading the portal), an admin
// of the cluster, or the blueprint's maintainers. An action that is not a wait names one of them.
var actorPhrase = regexp.MustCompile(`(?i)\b(you|an admin|the blueprint's maintainers)\b`)

// fieldName is an annotation key, a field path or a field name in an action (frontend, #667): the
// portal shows those under Details, not in the sentence.
var fieldName = regexp.MustCompile(`krateo\.io/|\bstatus\.|\bspec\.|\bmetadata\.|\bapiRef\b`)

// offVocabulary are the words the portal does not use: it says blueprint, data source and resources.
var offVocabulary = regexp.MustCompile(`(?i)\b(composition ?definitions?|definitions?|restactions?|children|child)\b`)

// cliStep is a command line in an action, which is on-screen text for a person, not a runbook.
var cliStep = regexp.MustCompile(`(?i)\bkubectl\b|\bhelm (rollback|upgrade|install|uninstall)\b`)

// statusFieldExists reports whether path (status.a.b) names a field of CompositionDefinitionStatus, by
// its json tags: the fields core-provider writes. A slice's elements are not descended into.
func statusFieldExists(path string) bool {
	parts := strings.Split(path, ".")
	if parts[0] != "status" {
		return false
	}
	typ := reflect.TypeOf(compositiondefinitionsv1alpha1.CompositionDefinitionStatus{})
	for i, p := range parts[1:] {
		for typ.Kind() == reflect.Pointer {
			typ = typ.Elem()
		}
		if typ.Kind() != reflect.Struct {
			return false
		}
		next, found := reflect.Type(nil), false
		for j := 0; j < typ.NumField(); j++ {
			name, _, _ := strings.Cut(typ.Field(j).Tag.Get("json"), ",")
			if name == p {
				next, found = typ.Field(j).Type, true
				break
			}
		}
		if !found {
			return false
		}
		typ = next
		if typ.Kind() == reflect.Slice && i < len(parts)-2 {
			return false
		}
	}
	return true
}

// Every reason carries the fields the JSON publishes (#667): an expected clearance, a since-version,
// an action unless it is healthy or steady, and detail fields that CompositionDefinitionStatus really
// has.
func TestEveryReasonHasItsAuthoredFields(t *testing.T) {
	// Control: the resolver must find a field core-provider writes, and refuse one it does not, or a
	// pass below would say nothing.
	if !statusFieldExists("status.migratedValues.refused") || statusFieldExists("status.migratedValues.nope") ||
		statusFieldExists("status.migratedValues.refused.fields") {
		t.Fatal("control: the status resolver does not tell a CompositionDefinitionStatus field from another path")
	}
	var types []string
	for _, r := range Table() {
		types = append(types, regexp.QuoteMeta(string(r.Type())))
	}
	// A condition type named in an action (Ready, Synced, ...), or the Sync button, which only re-reads.
	conditionTypes := regexp.MustCompile(`\b(` + strings.Join(append(types, "Sync"), "|") + `)\b`)
	withAction, withDetail := 0, 0
	for _, r := range Table() {
		key := fmt.Sprintf("%s/%s/%s/%s", r.Type(), r.Status(), r, r.Writer())
		switch r.Clears().Kind {
		case Steady, NextPass, Indefinite:
		default:
			t.Errorf("%s: no expected-to-clear class (%q)", key, r.Clears().Kind)
		}
		if r.Clears().Note == "" {
			t.Errorf("%s: an expected-to-clear class with no note", key)
		}
		if r.Since() == "" {
			t.Errorf("%s: no Since (a released tag, or %q)", key, Unreleased)
		}
		if r.Action() == "" && r.ParentVerdict() != Healthy && r.Clears().Kind != Steady {
			t.Errorf("%s: no Action; one is required unless the reason is healthy or steady", key)
		}
		if a := r.Action(); a != "" && !strings.HasPrefix(a, "Wait") && !actorPhrase.MatchString(a) {
			t.Errorf("%s: action %q is not a wait and names no actor (you, an admin, the blueprint's maintainers)", key, a)
		}
		if a := r.Action(); cliStep.MatchString(a) {
			t.Errorf("%s: action %q has a command-line step", key, a)
		}
		if a := r.Action(); fieldName.MatchString(a) || conditionTypes.MatchString(a) {
			t.Errorf("%s: action %q names an annotation, a field or a condition: plain words only (the annotation goes in Annotation)", key, a)
		}
		if a := r.Action(); offVocabulary.MatchString(a) {
			t.Errorf("%s: action %q says %q: the portal's words are blueprint, data source and resources", key, a, offVocabulary.FindString(a))
		}
		if c := r.Control(); c != "" && (!portalControls[c] || !strings.Contains(r.Action(), c)) {
			t.Errorf("%s: control %q is not one of %v, or the action does not name it", key, c, portalControls)
		}
		if a := r.Annotation(); a != nil && !strings.HasPrefix(a.Name, "krateo.io/") {
			t.Errorf("%s: annotation %q is not a krateo.io/ key", key, a.Name)
		}
		if r.Action() != "" {
			withAction++
		}
		for _, p := range r.DetailFields() {
			withDetail++
			if !statusFieldExists(p) {
				t.Errorf("%s: detail field %s is not a field of CompositionDefinitionStatus", key, p)
			}
		}
	}
	t.Logf("%d reasons, %d with an action, %d detail fields checked", len(Table()), withAction, withDetail)
	if withDetail == 0 {
		t.Fatal("no detail field was checked: the loop measured nothing")
	}
}

// Each row is unique, a Ready row has a parent verdict and a Synced row has none, and a True Ready
// is healthy: the rollup reads every True as healthy, so declaring anything else would be a row the
// cdc's test can only refuse.
func TestTableIsWellFormed(t *testing.T) {
	seen := map[string]bool{}
	ready := 0
	for _, r := range Table() {
		key := fmt.Sprintf("%s/%s/%s/%s", r.Type(), r, r.Status(), r.Writer())
		if seen[key] {
			t.Errorf("duplicate row %s", key)
		}
		seen[key] = true
		switch r.Type() {
		case rtv1.TypeReady:
			ready++
			if r.ParentVerdict() == NotRead {
				t.Errorf("%s: a Ready row needs a parent verdict", key)
			}
			if r.Status() == metav1.ConditionTrue && r.ParentVerdict() != Healthy {
				t.Errorf("%s: a True Ready rolls up healthy, declared %q", key, r.ParentVerdict())
			}
		case rtv1.TypeSynced, TypeControllerActive, TypeSchemaFullyEnforced, TypeSpecSchemaCurrent,
			TypeApiRefRBACComplete, TypeAuthnDelegation, TypeAuthnMappingApplied, TypeValuesSchemaAuthored, TypeMigratedValuesValid:
			if r.ParentVerdict() != NotRead {
				t.Errorf("%s: the rollup reads only Ready, declared %q", key, r.ParentVerdict())
			}
		default:
			t.Errorf("%s: a condition type the registry does not declare", key)
		}
		if r.Meaning() == "" {
			t.Errorf("%s: no meaning", key)
		}
	}
	if ready < 7 {
		t.Errorf("only %d Ready rows: the table lost rows", ready)
	}
}

// Every provider-runtime row matches what the runtime's own constructor builds, and every constructor
// listed has a row: a status written down by hand would drift from the runtime silently.
func TestRuntimeRowsMatchTheRuntime(t *testing.T) {
	built := map[string]bool{}
	for _, c := range RuntimeConstructors() {
		built[fmt.Sprintf("%s/%s/%s", c.Type, c.Reason, c.Status)] = true
	}
	rows := 0
	for _, r := range Table() {
		if r.Writer() != WriterRuntime {
			continue
		}
		rows++
		key := fmt.Sprintf("%s/%s/%s", r.Type(), r, r.Status())
		if !built[key] {
			t.Errorf("runtime row %s: no provider-runtime constructor builds it", key)
		}
		delete(built, key)
	}
	for k := range built {
		t.Errorf("provider-runtime builds %s, and the table has no row for it", k)
	}
	if rows == 0 {
		t.Fatal("no runtime rows: the check compared nothing")
	}
}

const runtimeAPIPkg = "github.com/krateo-platformops/provider-runtime/apis/common/v1"

// readyConstructors are provider-runtime's constructors of a Ready condition.
var readyConstructors = map[string]bool{"Available": true, "Creating": true, "Unavailable": true, "Deleting": true, "NotObserved": true}

// readyConstructionSites lists every place in file that builds a Ready condition: a call to one of
// the runtime's Ready constructors, a composite literal whose Type is the runtime's TypeReady or the
// literal "Ready", or the runtime's TypeReady passed to any call other than a condition read.
func readyConstructionSites(fset *token.FileSet, file *ast.File) []string {
	alias := ""
	for _, imp := range file.Imports {
		if p, _ := strconv.Unquote(imp.Path.Value); p == runtimeAPIPkg {
			alias = "v1"
			if imp.Name != nil {
				alias = imp.Name.Name
			}
		}
	}
	isRuntime := func(e ast.Expr, name func(string) bool) bool {
		se, ok := e.(*ast.SelectorExpr)
		if !ok || alias == "" {
			return false
		}
		id, ok := se.X.(*ast.Ident)
		return ok && id.Name == alias && name(se.Sel.Name)
	}
	isTypeReady := func(e ast.Expr) bool {
		if isRuntime(e, func(s string) bool { return s == "TypeReady" }) {
			return true
		}
		if bl, ok := e.(*ast.BasicLit); ok {
			u, err := strconv.Unquote(bl.Value)
			return err == nil && u == "Ready"
		}
		return false
	}
	var out []string
	ast.Inspect(file, func(n ast.Node) bool {
		switch n := n.(type) {
		case *ast.CallExpr:
			if isRuntime(n.Fun, func(s string) bool { return readyConstructors[s] }) {
				out = append(out, fset.Position(n.Pos()).String())
				return true
			}
			name := ""
			switch f := n.Fun.(type) {
			case *ast.SelectorExpr:
				name = f.Sel.Name
			case *ast.Ident:
				name = f.Name
			}
			if name == "GetCondition" {
				return true // a read
			}
			for _, a := range n.Args {
				if isRuntime(a, func(s string) bool { return s == "TypeReady" }) {
					out = append(out, fset.Position(a.Pos()).String())
				}
			}
		case *ast.KeyValueExpr:
			if k, ok := n.Key.(*ast.Ident); ok && k.Name == "Type" && isTypeReady(n.Value) {
				out = append(out, fset.Position(n.Pos()).String())
			}
		}
		return true
	})
	return out
}

// No CompositionDefinition Ready condition is built anywhere in core-provider except here, so the
// closed set above is the whole set. The type alone cannot stop a runtime constructor call or a
// literal; this does. Scope: the module, except internal/controllers/kubernetestargets, whose Ready
// is a KubernetesTarget's, a different kind with its own reasons. Control: the same detector must find
// this package's own constructions, or a zero elsewhere would say nothing.
func TestNoReadyConditionBuiltOutsideCdreason(t *testing.T) {
	root := "../.."
	fset := token.NewFileSet()
	scanned, controlHits := 0, 0
	mustVisit := map[string]bool{
		"main.go": false,
		"internal/controllers/compositiondefinitions/compositiondefinitions.go": false,
		"internal/controllers/compositiondefinitions/scaletozero.go":            false,
		"internal/cdreason/cdreason.go":                                         false,
	}
	var violations []string
	err := filepath.WalkDir(root, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		rel, _ := filepath.Rel(root, path)
		rel = filepath.ToSlash(rel)
		if d.IsDir() {
			if name := d.Name(); name == "vendor" || name == "testdata" || (strings.HasPrefix(name, ".") && path != root) ||
				rel == "internal/controllers/kubernetestargets" {
				return filepath.SkipDir
			}
			return nil
		}
		if !strings.HasSuffix(path, ".go") || strings.HasSuffix(path, "_test.go") {
			return nil
		}
		file, err := parser.ParseFile(fset, path, nil, 0)
		if err != nil {
			return err
		}
		scanned++
		if _, ok := mustVisit[rel]; ok {
			mustVisit[rel] = true
		}
		sites := readyConstructionSites(fset, file)
		if strings.HasPrefix(rel, "internal/cdreason/") {
			controlHits += len(sites)
			return nil
		}
		violations = append(violations, sites...)
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
	t.Logf("scanned %d files; control: %d constructions inside internal/cdreason", scanned, controlHits)
	for f, seen := range mustVisit {
		if !seen {
			t.Fatalf("the scan never reached %s (%d files scanned): it is not measuring the module", f, scanned)
		}
	}
	if controlHits == 0 {
		t.Fatal("control: the detector found no construction inside internal/cdreason, so a zero elsewhere says nothing")
	}
	for _, v := range violations {
		t.Errorf("Ready condition built outside internal/cdreason: %s (use a cdreason.Reason)", v)
	}
}
