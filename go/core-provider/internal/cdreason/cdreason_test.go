// jsonVerdicts are the JSON's verdict values: a closed enum a consumer can switch on, where the
// markdown cell is prose. NotRead (the markdown's "—") is JSON null.
var jsonVerdicts = map[string]bool{"healthy": true, "converging": true, "failed": true, "unevaluated": true}

// jsonVerdict maps a Verdict to the JSON's verdict and rollsUpAs: Unevaluated, "unevaluated (rolls up
// as healthy)", becomes verdict "unevaluated" with rollsUpAs "healthy". A Verdict this mapping does not
// know fails the render rather than publishing prose as an enum value.
func jsonVerdict(t *testing.T, v Verdict) (*string, string) {
	t.Helper()
	var word, as string
	switch v {
	case NotRead:
		return nil, ""
	case Healthy, Converging, Failed:
		word = string(v)
	case Unevaluated:
		word, as = "unevaluated", "healthy"
	default:
		t.Fatalf("verdict %q: no JSON verdict for it", v)
	}
	return &word, as
}

// markdownVerdict is the markdown cell a JSON entry's verdict and rollsUpAs stand for: jsonVerdict
// inverted, so the JSON-to-markdown comparison checks the mapping as well as the rows.
func markdownVerdict(verdict *string, rollsUpAs string) string {
	switch {
	case verdict == nil:
		return string(NotRead)
	case *verdict == "unevaluated":
		return "unevaluated (rolls up as " + rollsUpAs + ")"
	}
	return *verdict
}

// The JSON's verdict is the enum or null and nothing else, in the rendering and in the committed
// file, decoded as a consumer decodes it (a generic map, not this test's own struct): healthy,
// converging, failed or unevaluated, null exactly where the condition is not Ready, and rollsUpAs
// present exactly on unevaluated entries.
func TestCDReadyReasonsJSONVerdictsAreTheEnum(t *testing.T) {
	committed, err := os.ReadFile(cdReadyReasonsJSON)
	if err != nil {
		t.Fatal(err)
	}
	for _, src := range []struct{ name, body string }{{"rendered", renderCDReadyReasonsJSON(t)}, {cdReadyReasonsJSON, string(committed)}} {
		var f struct {
			Reasons []map[string]any `json:"reasons"`
		}
		if err := json.Unmarshal([]byte(src.body), &f); err != nil {
			t.Fatalf("%s: %v", src.name, err)
		}
		counts := map[string]int{}
		for i, e := range f.Reasons {
			v, present := e["verdict"]
			if !present {
				t.Errorf("%s entry %d (%v): no verdict key", src.name, i, e["reason"])
				continue
			}
			word := "null"
			if v != nil {
				s, ok := v.(string)
				if !ok || !jsonVerdicts[s] {
					t.Errorf("%s entry %d (%v): verdict %#v is not one of healthy, converging, failed, unevaluated or null", src.name, i, e["reason"], v)
					continue
				}
				word = s
			}
			counts[word]++
			if (v == nil) != (e["condition"] != "Ready") {
				t.Errorf("%s entry %d (%v/%v): verdict %v; null is for, and only for, a condition the rollup does not read", src.name, i, e["condition"], e["reason"], v)
			}
			as, hasAs := e["rollsUpAs"]
			if hasAs != (word == "unevaluated") {
				t.Errorf("%s entry %d (%v): rollsUpAs %v with verdict %s", src.name, i, e["reason"], as, word)
			}
			if hasAs && as != "healthy" {
				t.Errorf("%s entry %d (%v): rollsUpAs %v, want healthy", src.name, i, e["reason"], as)
			}
		}
		t.Logf("%s: %d entries, verdicts %v", src.name, len(f.Reasons), counts)
		if counts["null"] == 0 || counts["healthy"] == 0 {
			t.Errorf("%s: control: verdicts %v have no null or no healthy entry; the check measured nothing", src.name, counts)
		}
	}
}

func renderCDReadyReasonsJSON(t *testing.T) string {
	t.Helper()
	f := jsonFile{
		SchemaVersion: 1,
		Table:         "cd-ready-reasons",
		GeneratedFrom: reflect.TypeOf(Reason{}).PkgPath(),
		Notice:        cdReadyReasonsNotice,
		Reasons:       []jsonReason{},
		Deprecated:    []jsonRemoved{},
	}
	for _, r := range Table() {
		verdict, rollsUpAs := jsonVerdict(t, r.ParentVerdict())
		f.Reasons = append(f.Reasons, jsonReason{
			Condition: string(r.Type()), Reason: r.String(), Status: string(r.Status()), Verdict: verdict, RollsUpAs: rollsUpAs,
			Writer: string(r.Writer()), Clearance: jsonClearance{Kind: string(r.Clears().Kind), Detail: r.Clears().Note},
			Meaning: r.Meaning(), SinceVersion: r.Since(), Action: r.Action(), DetailFields: append([]string{}, r.DetailFields()...),
		})
	}
	for _, d := range Deprecated() {
		f.Deprecated = append(f.Deprecated, jsonRemoved{
			Condition: string(d.Condition), Reason: string(d.Reason), Status: string(d.Status), Writer: string(d.Writer),
			RemovedIn: d.RemovedIn, Note: d.Note,
		})
	}
	var b bytes.Buffer
	enc := json.NewEncoder(&b)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(f); err != nil {
		t.Fatal(err)
	}
	return b.String()
}

// The rendered table is committed, and stale is a failure: a reason added, removed, re-statused or
// re-classified changes the file in the same change, where a consumer diffing tags sees it. Both
// renderings are checked, the markdown and the JSON (#667), each against its own committed file:
// either one stale fails.
func TestCDReadyReasonTableIsCurrent(t *testing.T) {
	for _, doc := range []struct {
		path string
		want string
	}{
		{cdReadyReasonsDoc, renderCDReadyReasons()},
		{cdReadyReasonsJSON, renderCDReadyReasonsJSON(t)},
	} {
		if os.Getenv("UPDATE_READY_REASONS") == "1" {
			if err := os.WriteFile(doc.path, []byte(doc.want), 0o644); err != nil {
				t.Fatal(err)
			}
		}
		got, err := os.ReadFile(doc.path)
		if err != nil {
			t.Errorf("%v (run with UPDATE_READY_REASONS=1 to create it)", err)
			continue
		}
		if string(got) != doc.want {
			t.Errorf("%s is stale: run `UPDATE_READY_REASONS=1 go test ./internal/cdreason/ -run TestCDReadyReasonTableIsCurrent` and commit it.\n--- want\n%s", doc.path, doc.want)
		}
	}
}

// The JSON is the markdown's table, entry for row: the same count, the same keys in the same order,
// the same verdict and meaning. A renderer that dropped or reordered an entry would agree with its
// own committed file and still disagree with the table consumers already parse. Read from the
// committed files, as a consumer reads them.
func TestCDReadyReasonsJSONMatchesTheMarkdown(t *testing.T) {
	raw, err := os.ReadFile(cdReadyReasonsDoc)
	if err != nil {
		t.Fatal(err)
	}
	var header []string
	var rows []map[string]string
	for _, line := range strings.Split(string(raw), "\n") {
		if !strings.HasPrefix(line, "| ") {
			continue
		}
		cells := strings.Split(strings.TrimSuffix(strings.TrimPrefix(line, "| "), " |"), " | ")
		if header == nil {
			header = cells
			continue
		}
		if len(cells) != len(header) {
			t.Fatalf("%s: a row with %d cells under %d columns: %q", cdReadyReasonsDoc, len(cells), len(header), line)
		}
		row := map[string]string{}
		for i, c := range cells {
			row[header[i]] = c
		}
		rows = append(rows, row)
	}
	raw, err = os.ReadFile(cdReadyReasonsJSON)
	if err != nil {
		t.Fatal(err)
	}
	var f jsonFile
	if err := json.Unmarshal(raw, &f); err != nil {
		t.Fatalf("%s: %v", cdReadyReasonsJSON, err)
	}
	t.Logf("%d markdown rows, %d JSON entries", len(rows), len(f.Reasons))
	if len(rows) < 40 {
		t.Fatalf("only %d rows parsed from %s: the parser is not reading the table", len(rows), cdReadyReasonsDoc)
	}
	if len(f.Reasons) != len(rows) {
		t.Fatalf("%s has %d entries, %s has %d rows", cdReadyReasonsJSON, len(f.Reasons), cdReadyReasonsDoc, len(rows))
	}
	for i, e := range f.Reasons {
		r := rows[i]
		got := []string{e.Condition, "`" + e.Reason + "`", e.Status, e.Writer, markdownVerdict(e.Verdict, e.RollsUpAs), e.Meaning}
		want := []string{r["condition"], r["reason"], r["status"], r["writer"], r["parent verdict"], r["written by"]}
		if strings.Join(got, "|") != strings.Join(want, "|") {
			t.Errorf("entry %d: JSON %q, markdown %q", i, got, want)
		}
	}
}

// statusFieldExists reports whether path (status.a.b) names a field of CompositionDefinitionStatus, by
// its json tags: the fields core-provider writes. A slice's elements are not descended into.
func statusFieldExists(path string) bool {
	parts := strings.Split(path, ".")
	if parts[0] != "status" {
		return false
	}
	typ := reflect.TypeOf(compositiondefinitionsv1alpha1.CompositionDefinitionStatus{})
	for i, p := range parts[1:] {
		for typ.Kind() == reflect.Pointer {
			typ = typ.Elem()
		}
		if typ.Kind() != reflect.Struct {
			return false
		}
		next, found := reflect.Type(nil), false
		for j := 0; j < typ.NumField(); j++ {
			name, _, _ := strings.Cut(typ.Field(j).Tag.Get("json"), ",")
			if name == p {
				next, found = typ.Field(j).Type, true
				break
			}
		}
		if !found {
			return false
		}
		typ = next
		if typ.Kind() == reflect.Slice && i < len(parts)-2 {
			return false
		}
	}
	return true
}

// Every reason carries the fields the JSON publishes (#667): an expected clearance, a since-version,
// an action unless it is healthy or steady, and detail fields that CompositionDefinitionStatus really
// has.
func TestEveryReasonHasItsAuthoredFields(t *testing.T) {
	// Control: the resolver must find a field core-provider writes, and refuse one it does not, or a
	// pass below would say nothing.
	if !statusFieldExists("status.migratedValues.refused") || statusFieldExists("status.migratedValues.nope") ||
		statusFieldExists("status.migratedValues.refused.fields") {
		t.Fatal("control: the status resolver does not tell a CompositionDefinitionStatus field from another path")
	}
	withAction, withDetail := 0, 0
	for _, r := range Table() {
		key := fmt.Sprintf("%s/%s/%s/%s", r.Type(), r.Status(), r, r.Writer())
		switch r.Clears().Kind {
		case Steady, NextPass, Indefinite:
		default:
			t.Errorf("%s: no expected-to-clear class (%q)", key, r.Clears().Kind)
		}
		if r.Clears().Note == "" {
			t.Errorf("%s: an expected-to-clear class with no note", key)
		}
		if r.Since() == "" {
			t.Errorf("%s: no Since (a released tag, or %q)", key, Unreleased)
		}
		if r.Action() == "" && r.ParentVerdict() != Healthy && r.Clears().Kind != Steady {
			t.Errorf("%s: no Action; one is required unless the reason is healthy or steady", key)
		}
		if r.Action() != "" {
			withAction++
		}
		for _, p := range r.DetailFields() {
			withDetail++
			if !statusFieldExists(p) {
				t.Errorf("%s: detail field %s is not a field of CompositionDefinitionStatus", key, p)
			}
		}
	}
	t.Logf("%d reasons, %d with an action, %d detail fields checked", len(Table()), withAction, withDetail)
	if withDetail == 0 {
		t.Fatal("no detail field was checked: the loop measured nothing")
	}
}

// Each row is unique, a Ready row has a parent verdict and a Synced row has none, and a True Ready
// is healthy: the rollup reads every True as healthy, so declaring anything else would be a row the
// cdc's test can only refuse.
func TestTableIsWellFormed(t *testing.T) {
	seen := map[string]bool{}
	ready := 0
	for _, r := range Table() {
		key := fmt.Sprintf("%s/%s/%s/%s", r.Type(), r, r.Status(), r.Writer())
		if seen[key] {
			t.Errorf("duplicate row %s", key)
		}
		seen[key] = true
		switch r.Type() {
		case rtv1.TypeReady:
			ready++
			if r.ParentVerdict() == NotRead {
				t.Errorf("%s: a Ready row needs a parent verdict", key)
			}
			if r.Status() == metav1.ConditionTrue && r.ParentVerdict() != Healthy {
				t.Errorf("%s: a True Ready rolls up healthy, declared %q", key, r.ParentVerdict())
			}
		case rtv1.TypeSynced, TypeControllerActive, TypeSchemaFullyEnforced, TypeSpecSchemaCurrent,
			TypeApiRefRBACComplete, TypeAuthnDelegation, TypeAuthnMappingApplied, TypeValuesSchemaAuthored, TypeMigratedValuesValid:
			if r.ParentVerdict() != NotRead {
				t.Errorf("%s: the rollup reads only Ready, declared %q", key, r.ParentVerdict())
			}
		default:
			t.Errorf("%s: a condition type the registry does not declare", key)
		}
		if r.Meaning() == "" {
			t.Errorf("%s: no meaning", key)
		}
	}
	if ready < 7 {
		t.Errorf("only %d Ready rows: the table lost rows", ready)
	}
}

