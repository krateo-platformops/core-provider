package compositiondefinitions

import (
	"fmt"
	"github.com/krateo-platformops/core-provider/internal/cdreason"

	crdutils "github.com/krateo-platformops/core-provider/internal/tools/crd/generation"
	rtv1 "github.com/krateo-platformops/provider-runtime/apis/common/v1"
	apiextensionsv1 "k8s.io/apiextensions-apiserver/pkg/apis/apiextensions/v1"
)

// conditionTypeSpecSchemaCurrent says whether the CRD version this definition serves carries the
// spec schema the generator produces today (core-provider#534).
//
// A version's spec schema used to be written once, when the version was added, so a generator fix
// never reached a version already served. It is now refreshed when the new render is PROVABLY
// looser (generation.CompareSpec, an allowlist of loosening moves), and kept otherwise. This
// condition is the record of which happened: recomputed on every Observe from the current render,
// like SchemaFullyEnforced, so it clears as soon as served and generated agree.
// Its reasons are cdreason.SpecSchemaCurrent (identical), SpecSchemaLooserPending (transient: the next
// Update writes the looser render), SpecSchemaNotLooser (kept until the chart version changes) and
// SpecSchemaOwnedElsewhere (a follower).
const conditionTypeSpecSchemaCurrent = cdreason.TypeSpecSchemaCurrent

// specDriftDecision is Observe's whole #534 decision, extracted so it is tested rather than read: the
// condition to set, and whether Observe must route to Update (only for a provably looser render;
// ProjectWrite then writes it). Anything else is reported and left as served.
func specDriftDecision(live, generated *apiextensionsv1.CustomResourceDefinition) (rtv1.Condition, bool, crdutils.SpecDrift, error) {
	d, err := crdutils.CompareSpec(live, generated)
	if err != nil {
		return rtv1.Condition{}, false, d, fmt.Errorf("error comparing CRD spec schema: %w", err)
	}
	return specSchemaCurrentCondition(d), d.Looser(), d, nil
}

func specSchemaCurrentCondition(d crdutils.SpecDrift) rtv1.Condition {
	switch {
	case d.Equal:
		return cdreason.SpecSchemaCurrent.WithMessage(fmt.Sprintf("the CRD serves %s with the spec schema generated from the chart", d.Version))
	case d.DefaultsOnly:
		return cdreason.SpecSchemaLooserPending.WithMessage(fmt.Sprintf("the spec schema generated for %s differs from the served one only in its defaults (now the chart's values.yaml's); it is being written", d.Version))
	case d.Looser():
		return cdreason.SpecSchemaLooserPending.WithMessage(fmt.Sprintf("the spec schema generated for %s is looser than the served one; it is being written", d.Version))
	default:
		return cdreason.SpecSchemaNotLooser.WithMessage(fmt.Sprintf("the spec schema generated for %s differs from the served one in %d way(s) that are not provably "+
			"looser, so the served schema is kept and takes the new one only with the next chart version: %s",
			d.Version, len(d.NotLooser), capJoin(d.NotLooser, maxWarningsInConditionMessage)))
	}
}

func specSchemaOwnedElsewhereCondition(ownerNamespace, ownerName string) rtv1.Condition {
	return cdreason.SpecSchemaOwnedElsewhere.WithMessage(
		fmt.Sprintf("the CRD is generated by CompositionDefinition %s/%s; see its %s condition", ownerNamespace, ownerName, conditionTypeSpecSchemaCurrent))
}
