package compositiondefinitions

import (
	"fmt"
	"sort"
	"strings"

	"github.com/krateo-platformops/plumbing/crdgen"
	rtv1 "github.com/krateo-platformops/provider-runtime/apis/common/v1"
	corev1 "k8s.io/api/core/v1"
	metav1 "k8s.io/apimachinery/pkg/apis/meta/v1"
	"k8s.io/apimachinery/pkg/runtime"
	"k8s.io/client-go/tools/events"
)

// conditionTypeSchemaFullyEnforced says whether the generated CRD enforces everything the
// blueprint's values.schema.json states (#362).
//
// crdgen cannot express every JSON Schema construct as a structural CRD, and where it cannot it drops
// or loosens the constraint. The author was never told: the CRD installed, and the constraint was
// simply not enforced. This condition is the durable record. It is recomputed on EVERY Observe from
// the warnings of the CURRENT render, so it clears as soon as a schema change makes everything
// expressible. An Event alone could not be the record: Events expire after an hour, and generation
// (when they would fire) is rare for a stable definition.
//
// It counts only warnings whose Kind.LosesEnforcement() is true, i.e. the CRD accepts values the
// schema rejects. Since plumbing v1.27.0 crdgen also reports things that lose nothing (a parent given
// default {}, an observedGeneration declared with another type), and counting those would read False
// on most definitions (decided by Diego, 2026-11-05).
const conditionTypeSchemaFullyEnforced rtv1.ConditionType = "SchemaFullyEnforced"

const (
	reasonSchemaFullyEnforced     rtv1.ConditionReason = "FullyEnforced"
	reasonSchemaNotFullyEnforced  rtv1.ConditionReason = "ConstraintsNotEnforced"
	reasonSchemaOwnedElsewhere    rtv1.ConditionReason = "OwnedByAnotherDefinition"
	maxWarningsInConditionMessage                      = 10
)

// schemaEnforcedCondition computes the condition from the warnings of the current render.
func schemaEnforcedCondition(warnings []crdgen.Warning) rtv1.Condition {
	c := rtv1.Condition{Type: conditionTypeSchemaFullyEnforced, LastTransitionTime: metav1.Now()}
	lost := describeWarnings(warnings, true)
	if len(lost) == 0 {
		c.Status, c.Reason = metav1.ConditionTrue, reasonSchemaFullyEnforced
		c.Message = "the generated CRD enforces every constraint in the chart's values schema"
		return c
	}
	c.Status, c.Reason = metav1.ConditionFalse, reasonSchemaNotFullyEnforced
	c.Message = fmt.Sprintf("the generated CRD does not enforce %d constraint(s) from the chart's values "+
		"schema, so the cluster accepts values the schema rejects: %s", len(lost), capJoin(lost, maxWarningsInConditionMessage))
	return c
}

// schemaOwnedElsewhereCondition is the condition for a follower definition: it does not generate the
// CRD, the owner does, so it has no verdict of its own to give. Unknown rather than a stale value
// left from a time it owned the Kind.
func schemaOwnedElsewhereCondition(ownerNamespace, ownerName string) rtv1.Condition {
	return rtv1.Condition{
		Type: conditionTypeSchemaFullyEnforced, Status: metav1.ConditionUnknown, LastTransitionTime: metav1.Now(),
		Reason:  reasonSchemaOwnedElsewhere,
		Message: fmt.Sprintf("the CRD is generated by CompositionDefinition %s/%s; see its %s condition", ownerNamespace, ownerName, conditionTypeSchemaFullyEnforced),
	}
}

// describeWarnings renders the warnings whose LosesEnforcement() equals losing, sorted, so an
// unchanged render produces an unchanged condition message and no status churn.
func describeWarnings(warnings []crdgen.Warning, losing bool) []string {
	var out []string
	for _, w := range warnings {
		if w.Kind.LosesEnforcement() == losing {
			out = append(out, w.String())
		}
	}
	sort.Strings(out)
	return out
}

func capJoin(items []string, max int) string {
	if len(items) <= max {
		return strings.Join(items, "; ")
	}
	return strings.Join(items[:max], "; ") + fmt.Sprintf("; and %d more", len(items)-max)
}

// emitSchemaEvents publishes the warnings as Events, only when crdgen actually ran (fresh): a new
// schema, or the first render in this process. That is the "this just happened" moment. The
// condition carries the standing fact on every pass.
func emitSchemaEvents(rec events.EventRecorder, obj runtime.Object, warnings []crdgen.Warning, fresh bool) {
	if !fresh || rec == nil {
		return
	}
	if lost := describeWarnings(warnings, true); len(lost) > 0 {
		rec.Eventf(obj, nil, corev1.EventTypeWarning, "SchemaConstraintsNotEnforced", "GenerateCRD",
			"%d constraint(s) from the values schema are not enforced by the generated CRD: %s",
			len(lost), capJoin(lost, maxWarningsInConditionMessage))
	}
	if notes := describeWarnings(warnings, false); len(notes) > 0 {
		rec.Eventf(obj, nil, corev1.EventTypeNormal, "SchemaGenerationNotes", "GenerateCRD",
			"%d note(s) from generating the CRD (nothing is lost): %s",
			len(notes), capJoin(notes, maxWarningsInConditionMessage))
	}
}
