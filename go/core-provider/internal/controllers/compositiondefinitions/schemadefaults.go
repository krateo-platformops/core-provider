package compositiondefinitions

import (
	"fmt"
	"sort"

	"github.com/krateo-platformops/core-provider/internal/cdreason"
	"github.com/krateo-platformops/core-provider/internal/tools/chart"
	crdutils "github.com/krateo-platformops/core-provider/internal/tools/crd/generation"
	rtv1 "github.com/krateo-platformops/provider-runtime/apis/common/v1"
	apiextensionsv1 "k8s.io/apiextensions-apiserver/pkg/apis/apiextensions/v1"
	"k8s.io/apimachinery/pkg/runtime/schema"
)

// maxDefaultDifferencesInMessage bounds the SchemaDefaultsMatchValues message.
const maxDefaultDifferencesInMessage = 10

// generatedFromChart is the CRD for a chart (#686): crdgen's render of its values.schema.json, with
// every default then taken from its values.yaml (crdutils.ApplyValuesDefaults), so a Composition
// and a `helm install` of the chart agree by construction. Every place that generates a CRD for a
// definition goes through here, so the served CRD, the one Create applies and the one Update applies
// cannot disagree about defaults.
//
// A values.yaml that exists and cannot be read is an error, not "no values": reading it as empty
// would strip every default from the CRD.
func generatedFromChart(spec chart.SpecSchemaResult, gvk schema.GroupVersionKind) (crdutils.Generated, []crdutils.DefaultDifference, error) {
	if spec.ValuesErr != nil {
		return crdutils.Generated{}, nil, spec.ValuesErr
	}
	g, err := crdutils.GenerateCRDWithWarnings(spec.Bytes, gvk)
	if err != nil {
		return crdutils.Generated{}, nil, err
	}
	return g, crdutils.ApplyValuesDefaults(g.CRD, spec.Values), nil
}

// crdFromChart is generatedFromChart for the callers that need only the CRD.
func crdFromChart(spec chart.SpecSchemaResult, gvk schema.GroupVersionKind) (*apiextensionsv1.CustomResourceDefinition, error) {
	g, _, err := generatedFromChart(spec, gvk)
	if err != nil {
		return nil, err
	}
	return g.CRD, nil
}

// schemaDefaultsCondition says whether the chart's values.schema.json defaults agree with its
// values.yaml, which the generated CRD follows (#686). Informational: Ready does not read it. The
// differences are sorted, so an unchanged chart produces an unchanged message.
func schemaDefaultsCondition(spec chart.SpecSchemaResult, invalid []crdutils.DefaultDifference) rtv1.Condition {
	diffs := append(crdutils.SchemaDefaultDifferences(spec.Bytes, spec.Values), invalid...)
	if len(diffs) == 0 {
		return cdreason.SchemaDefaultsAligned.WithMessage("every default in the chart's values.schema.json equals the value in its values.yaml")
	}
	sort.SliceStable(diffs, func(i, j int) bool { return diffs[i].Path < diffs[j].Path })
	return cdreason.SchemaDefaultsDiffer.WithMessage(fmt.Sprintf(
		"%d default(s) in the chart's values.schema.json disagree with its values.yaml; the generated CRD uses values.yaml's, as helm does: %s",
		len(diffs), crdutils.DescribeDifferences(diffs, maxDefaultDifferencesInMessage)))
}

// schemaDefaultsOwnedElsewhereCondition is the follower's: it does not generate the CRD.
func schemaDefaultsOwnedElsewhereCondition(ownerNamespace, ownerName string) rtv1.Condition {
	return cdreason.SchemaDefaultsOwnedElsewhere.WithMessage(
		fmt.Sprintf("the CRD is generated by CompositionDefinition %s/%s; see its %s condition", ownerNamespace, ownerName, cdreason.TypeSchemaDefaultsMatchValues))
}
