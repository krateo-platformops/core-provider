package compositiondefinitions

import (
	"fmt"
	"strings"

	"github.com/krateo-platformops/core-provider/internal/cdreason"
	"github.com/krateo-platformops/core-provider/internal/tools/chart"
	"github.com/krateo-platformops/plumbing/crdgen"
	"github.com/krateo-platformops/plumbing/valuesschema"
	rtv1 "github.com/krateo-platformops/provider-runtime/apis/common/v1"
)

// maxUntypedPathsInMessage bounds the untyped paths named in ValuesSchemaAuthored=False's message.
const maxUntypedPathsInMessage = 10

// valuesSchemaAuthoredCondition says where the definition's spec schema came from (#568 D6):
// True/Authored for the chart's own values.schema.json, False/InferredFromValues for one inferred
// under the opt-in, naming the rules version and the untyped paths (the first few). Stable while the
// chart is: the paths come sorted from the report's document order, and no counts that change
// between passes go into it.
func valuesSchemaAuthoredCondition(s chart.SpecSchemaResult) rtv1.Condition {
	if s.Source != chart.SchemaInferred || s.Report == nil {
		return cdreason.ValuesSchemaAuthored.WithMessage("the chart ships values.schema.json at its root")
	}
	var untyped []string
	for _, f := range s.Report.Findings {
		if f.Kind == valuesschema.KindUntyped {
			untyped = append(untyped, f.Path)
		}
	}
	msg := fmt.Sprintf("the chart ships no values.schema.json; the spec schema is inferred from values.yaml (%s: %s, rules %s): typed-open, with no authored constraints",
		chart.ValuesSchemaAnnotation, chart.ValuesSchemaInfer, s.Report.RulesVersion)
	if len(untyped) > 0 {
		shown := untyped
		if len(shown) > maxUntypedPathsInMessage {
			shown = shown[:maxUntypedPathsInMessage]
		}
		msg += fmt.Sprintf("; %d path(s) accept any value: %s", len(untyped), strings.Join(shown, ", "))
		if len(untyped) > len(shown) {
			msg += ", ..."
		}
	}
	return cdreason.ValuesSchemaInferred.WithMessage(msg)
}

// schemaSourceConditions are the owner's two schema conditions for the current render (#568 D6).
// ValuesSchemaAuthored says where the schema came from. SchemaFullyEnforced is computed from crdgen's
// warnings for an authored schema; for an inferred one it is Unknown/SchemaInferred, because an
// inferred schema has no authored constraints, so True ("authored constraints, all enforced") cannot
// be claimed for it (installer's point).
func schemaSourceConditions(s chart.SpecSchemaResult, warnings []crdgen.Warning) []rtv1.Condition {
	enforced := schemaEnforcedCondition(warnings)
	if s.Source == chart.SchemaInferred {
		enforced = cdreason.SchemaInferred.WithMessage("the spec schema is inferred from the chart's values.yaml, so it carries no authored constraints to enforce; see ValuesSchemaAuthored")
	}
	return []rtv1.Condition{enforced, valuesSchemaAuthoredCondition(s)}
}

// valuesSchemaOwnedElsewhereCondition is the follower's: it does not generate the CRD.
func valuesSchemaOwnedElsewhereCondition(ownerNamespace, ownerName string) rtv1.Condition {
	return cdreason.ValuesSchemaOwnedElsewhere.WithMessage(
		fmt.Sprintf("the CRD is generated by CompositionDefinition %s/%s; see its %s condition", ownerNamespace, ownerName, cdreason.TypeValuesSchemaAuthored))
}
